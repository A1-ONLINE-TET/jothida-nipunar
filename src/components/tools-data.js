// ── எண் கணிதம் (Chaldean முறை) ──────────────────────────────────────
const CHALDEAN = { A: 1, I: 1, J: 1, Q: 1, Y: 1, B: 2, K: 2, R: 2, C: 3, G: 3, L: 3, S: 3, D: 4, M: 4, T: 4, E: 5, H: 5, N: 5, X: 5, U: 6, V: 6, W: 6, O: 7, Z: 7, F: 8, P: 8 };
const reduce = (n) => { let x = Math.abs(n); while (x > 9) x = String(x).split("").reduce((a, d) => a + Number(d), 0); return x; };
const digitsSum = (s) => String(s).replace(/\D/g, "").split("").reduce((a, d) => a + Number(d), 0);

// dob: "DD.MM.YYYY"; name: ஆங்கில எழுத்துக்களில். திரும்புவது: { birth, destiny, name, nameTotal }
export function numerologyOf(dob, name) {
  const m = /^(\d{2})\.(\d{2})\.(\d{4})$/.exec(dob || "");
  const letters = String(name || "").toUpperCase().replace(/[^A-Z]/g, "");
  const nameTotal = letters.split("").reduce((a, c) => a + (CHALDEAN[c] || 0), 0);
  return {
    birth: m ? reduce(Number(m[1])) : null,
    destiny: m ? reduce(digitsSum(dob)) : null,
    name: letters ? reduce(nameTotal) : null,
    nameTotal: letters ? nameTotal : null,
  };
}

