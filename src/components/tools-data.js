const hmToMin = (hm) => { const [h, m] = String(hm).split(":").map(Number); return h * 60 + (m || 0); };
const minToHm = (min) => { const t = ((Math.round(min) % 1440) + 1440) % 1440; return `${String(Math.floor(t / 60)).padStart(2, "0")}:${String(t % 60).padStart(2, "0")}`; };

// sunrise / sunset / nextSunrise — "HH:MM" (24 மணி). 16 பாகங்களும் நேரத்துடன்.
export function gowriForDay(weekday, sunrise, sunset, nextSunrise) {
  const sr = hmToMin(sunrise), ss = hmToMin(sunset), nsr = hmToMin(nextSunrise || sunrise) + 1440;
  const row = GOWRI_TABLE[weekday];
  const build = (codes, start, end) => {
    const seg = (end - start) / 8;
    return [...codes].map((c, i) => ({ ...GOWRI_NAMES[c], from: minToHm(start + i * seg), to: minToHm(start + (i + 1) * seg) }));
  };
  return { day: build(row.day, sr, ss), night: build(row.night, ss, nsr) };
}

